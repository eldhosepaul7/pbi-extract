#!/usr/bin/env python3
"""
list_metrics.py - Build the metric list straight from the model's measure names.

Usage:
    python list_metrics.py --out out

No Power BI knowledge needed. Measures are grouped by their core name, so
Total_AllowedAmount_Medical, Prior_AllowedAmount_Medical and Allowed%Change_Medical
become one metric, "Allowed Amount" (Medical). For each metric it picks the base measure
(Total_X if it exists, otherwise Current_X) and lists its variants.

Writes:
    out/metric_inventory.csv   one row per metric: name, domain, base measure, variants, display folders
    base_metrics_auto.txt      ready-to-use base list for analyze_model.py:
                               delete the lines for metrics business users don't need, then
                               python analyze_model.py --out out --base-metrics base_metrics_auto.txt
Standard library only. Reads out/measures.json from extract_bim.py.
"""
import argparse
import csv
import json
import os
import re
from collections import defaultdict

from analyze_model import STEM_DROP, name_variants, split_camel, stem

QUALIFIER_WORDS = {"brand", "generic", "specialty", "specialist", "mail order", "mailorder", "retail",
                   "inpatient", "outpatient", "professional", "facility", "oon", "inn", "in network",
                   "out network", "behavioral", "emergency", "urgent", "primary", "ancillary"}
METRIC_ACRONYMS = {"PMPM", "PMPY", "PKPY", "ALOS", "K", "YTD", "MTD", "QTD", "YOY", "KPI"}
UI_RE = re.compile(r"(?i)selector|slicer|colou?r|title|label|tooltip|icon|^show|flag")
PREFIX_RE = re.compile(r"^(Total|Current|Prior|Previous|CY|PY)_", re.I)
KNOWN_DOMAINS = ("medical", "pharmacy", "dental", "vision", "behavioral")


def domain_of(name):
    m = re.search(r"_(" + "|".join(KNOWN_DOMAINS) + r")(?:_[A-Za-z]+)?$", name, re.I)
    return m.group(1).capitalize() if m else ""


def readable(name):
    """Current_AllowedPerClaim_Medical -> Allowed Per Claim"""
    core = PREFIX_RE.sub("", name)
    core = re.sub(r"_(" + "|".join(KNOWN_DOMAINS) + r")(?:_[A-Za-z]+)?$", "", core, flags=re.I)
    core = core.replace("_", " ")
    return re.sub(r"\s+", " ", split_camel(core)).strip()


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--out", default="out")
    ap.add_argument("--base-file", default="base_metrics_auto.txt")
    args = ap.parse_args()

    measures = json.load(open(os.path.join(args.out, "measures.json"), encoding="utf-8"))
    families = defaultdict(list)
    ui = []
    for m in measures:
        n = m["name"]
        if UI_RE.search(n):
            ui.append(n)
            continue
        families[stem(n) or n.lower()].append(m)

    # Subtypes: a leading qualifier on another metric's name, e.g. IPA / OUT / PROF / PCP (acronyms) or
    # Brand / Generic / Mail Order / Specialty (known words): Current_IPAAllowedPerClaim is Allowed Per Claim
    # for IPA claims. In a metric view that is one metric plus a dimension, not a separate metric.
    keys = set(families)
    subtype_of = {}            # family key -> (parent key or virtual parent label, qualifier)
    virtual = defaultdict(list)
    for k, ms in families.items():
        sample = sorted((m["name"] for m in ms), key=len)[0]
        core = PREFIX_RE.sub("", re.sub(r"\(.*?\)", " ", sample))
        orig = [t for t in re.findall(r"[A-Za-z0-9]+", split_camel(core)) if t.lower() not in STEM_DROP]
        if len(orig) < 2:
            continue
        stoks = k.split()
        q, width = None, 0
        two = (orig[0] + " " + orig[1]).lower()
        if two in QUALIFIER_WORDS:
            q, width = two, 2
        elif (orig[0].isupper() and len(orig[0]) >= 2 and orig[0] not in METRIC_ACRONYMS) \
                or orig[0].lower() in QUALIFIER_WORDS:
            q, width = orig[0].lower(), 1
        if not q or " ".join(stoks[:width]) != q:
            continue
        parent = " ".join(stoks[width:])
        if parent in keys:
            subtype_of[k] = (parent, q)
        else:
            virtual[parent].append((k, q))
    for parent, kids in virtual.items():
        if len(kids) >= 2:  # e.g. PCP / PROF / Specialist Procedures with no overall Procedures measure
            for k, q in kids:
                subtype_of[k] = ("~" + parent, q)

    def top(k, seen=()):
        if k in subtype_of and k not in seen:
            return top(subtype_of[k][0], seen + (k,))
        return k

    rows, base_lines = [], ["# domain|measure name  (generated by list_metrics.py: delete metrics you don't need)"]
    for key, ms in families.items():
        names = [m["name"] for m in ms]
        totals = [n for n in names if re.match(r"(?i)^total_", n)]
        currents = [n for n in names if re.match(r"(?i)^(current|cy)_", n)]
        plain = [n for n in names if not name_variants(n)]
        if totals:
            base, how = sorted(totals, key=len)[0], "Total_ measure"
        elif currents:
            base, how = sorted(currents, key=len)[0], "Current_ measure (no Total_ exists)"
        elif plain:
            base, how = sorted(plain, key=len)[0], "only measure without a variant word"
        else:
            base, how = "", "no base found: every measure is a variant"
        variants = sorted({v for n in names if n != base for v in (name_variants(n) or ["other"])})
        folders = sorted({m.get("display_folder", "") for m in ms if m.get("display_folder")})
        dom = domain_of(base or names[0])
        rows.append({
            "metric": readable(base or names[0]), "domain": dom, "base_measure": base, "base_rule": how,
            "n_measures": len(names), "variant_types": ";".join(variants),
            "is_dq_or_helper": bool(re.search(r"(?i)_dq$|^_|helper|numberof", base or names[0])),
            "display_folders": ";".join(folders), "all_measures": ";".join(sorted(names)),
            "_key": key,
        })
    readable_by_key = {r["_key"]: r["metric"] for r in rows}
    for r in rows:
        if r["_key"] in subtype_of:
            parent_key = top(r["_key"])
            if parent_key.startswith("~"):
                label = " ".join(w.capitalize() for w in parent_key[1:].split()
                                 if w.lower() not in KNOWN_DOMAINS)
                r["subtype_of"] = f"{label} (no overall measure in the model)"
            else:
                r["subtype_of"] = readable_by_key.get(parent_key, parent_key)
            r["subtype"] = subtype_of[r["_key"]][1].upper()
        else:
            r["subtype_of"], r["subtype"] = "", ""
    rows.sort(key=lambda r: (r["domain"] or "~", r["subtype_of"] or r["metric"], bool(r["subtype_of"]),
                             -r["n_measures"], r["metric"]))
    for r in rows:
        if not r["base_measure"]:
            base_lines.append(f"# NO BASE: {r['metric']} ({r['domain'] or 'no domain'}): {r['all_measures'][:120]}")
        elif r["is_dq_or_helper"]:
            base_lines.append(f"# helper or DQ, usually not a business metric: {r['domain']}|{r['base_measure']}")
        else:
            prefix = f"{r['domain']}|" if r["domain"] else ""
            note = (f"subtype {r['subtype']} of {r['subtype_of']}" if r["subtype_of"]
                    else "CORE METRIC")
            base_lines.append(f"{prefix}{r['base_measure']}    # {r['metric']}, {r['n_measures']} measures, {note}")

    path = os.path.join(args.out, "metric_inventory.csv")
    with open(path, "w", newline="", encoding="utf-8") as f:
        w = csv.DictWriter(f, fieldnames=[k for k in rows[0].keys() if k != "_key"], extrasaction="ignore")
        w.writeheader()
        w.writerows(rows)
    with open(args.base_file, "w", encoding="utf-8") as f:
        f.write("\n".join(base_lines) + "\n")
    n_base = sum(1 for r in rows if r["base_measure"] and not r["is_dq_or_helper"])
    print(f"{len(measures)} measures -> {len(rows)} metric families ({n_base} with a base measure), "
          f"{len(ui)} selector or formatting measures set aside.")
    by_dom = defaultdict(int)
    for r in rows:
        if r["base_measure"] and not r["is_dq_or_helper"]:
            by_dom[r["domain"] or "no domain"] += 1
    print("Metrics by domain: " + ", ".join(f"{k} {v}" for k, v in sorted(by_dom.items())))
    core = defaultdict(int)
    for r in rows:
        if r["base_measure"] and not r["is_dq_or_helper"] and not r["subtype_of"]:
            core[r["domain"] or "no domain"] += 1
    n_sub = sum(1 for r in rows if r["subtype_of"])
    split_words = defaultdict(int)
    for r in rows:
        if r["subtype"]:
            split_words[r["subtype"]] += 1
    print(f"{n_sub} families are subtypes of another metric (split by: "
          + ", ".join(f"{w} {n}" for w, n in sorted(split_words.items(), key=lambda x: -x[1])[:12]) + ")")
    print("Core metrics after folding subtypes into dimensions: "
          + ", ".join(f"{k} {v}" for k, v in sorted(core.items())))
    print(f"Wrote {path} and {args.base_file}")


if __name__ == "__main__":
    main()
